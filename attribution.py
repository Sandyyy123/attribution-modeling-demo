"""
attribution.py - Shapley-value based contribution modeling.

Accurately attributes credit for an outcome (conversion, revenue, performance KPI)
across N contributing factors using the game-theoretic Shapley framework.
Works for: marketing attribution, feature contribution, team/agent attribution.
"""

import numpy as np
import pandas as pd
from itertools import combinations
from typing import Callable, List, Dict


def shapley_values(players: List[str],
                   characteristic_fn: Callable[[frozenset], float],
                   n_samples: int = 512,
                   seed: int = 42) -> Dict[str, float]:
    """
    Monte-Carlo Shapley value estimation.

    players           - list of contributing entities (channels, features, agents)
    characteristic_fn - v(S) -> float: value generated by coalition S
    n_samples         - permutation samples (exact for |players| <= 10, MC otherwise)
    returns           - dict mapping each player to its fair-share attribution
    """
    rng = np.random.default_rng(seed)
    n = len(players)
    shapley = {p: 0.0 for p in players}

    if n <= 10:
        # Exact Shapley via all permutations (feasible up to ~10 players)
        from itertools import permutations
        perms = list(permutations(players))
        rng.shuffle(perms)
        perms_to_use = perms[:n_samples]
    else:
        # Random permutation sampling
        perms_to_use = [rng.permutation(players).tolist() for _ in range(n_samples)]

    for perm in perms_to_use:
        coalition = frozenset()
        prev_val = characteristic_fn(coalition)
        for player in perm:
            coalition = coalition | {player}
            new_val = characteristic_fn(coalition)
            shapley[player] += (new_val - prev_val) / len(perms_to_use)
            prev_val = new_val

    return shapley


def normalize_attributions(raw: Dict[str, float]) -> Dict[str, float]:
    """Convert raw Shapley values to percentage contributions (sum = 100%)."""
    total = sum(abs(v) for v in raw.values())
    if total == 0:
        return {k: 0.0 for k in raw}
    return {k: round(v / total * 100, 2) for k, v in raw.items()}


