def marketing_mta_fn(conversion_data: pd.DataFrame) -> Callable:
    """
    Multi-touch attribution characteristic function.
    conversion_data: DataFrame with columns [channel, touchpoint_order, converted]
    Returns v(S) = fraction of conversions where at least one channel in S appeared.
    """
    converted = conversion_data[conversion_data["converted"] == 1]

    def v(coalition: frozenset) -> float:
        if not coalition:
            return 0.0
        mask = converted["channel"].isin(coalition)
        journeys_touched = converted[mask]["journey_id"].nunique()
        total_journeys = converted["journey_id"].nunique()
        return journeys_touched / max(total_journeys, 1)

    return v


def linear_model_fn(X: np.ndarray, y: np.ndarray) -> Callable:
    """
    Characteristic function based on R^2 gain from feature subsets.
    v(S) = R^2 of OLS regression using only features in S.
    """
    from sklearn.linear_model import LinearRegression
    from sklearn.metrics import r2_score

    def v(coalition: frozenset) -> float:
        if not coalition:
            return 0.0
        idx = list(coalition)
        model = LinearRegression().fit(X[:, idx], y)
        return max(r2_score(y, model.predict(X[:, idx])), 0.0)

    return v


