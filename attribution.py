def handle_outliers(df: pd.DataFrame, method: str = "iqr",
                    factor: float = 1.5) -> pd.DataFrame:
    """
    Clip outliers using IQR fencing or Z-score capping.
    method: 'iqr' or 'zscore'
    Returns cleaned DataFrame with outliers replaced by boundary values.
    """
    df = df.copy()
    numeric_cols = df.select_dtypes(include=np.number).columns
    for col in numeric_cols:
        if method == "iqr":
            q1, q3 = df[col].quantile([0.25, 0.75])
            iqr = q3 - q1
            lo, hi = q1 - factor * iqr, q3 + factor * iqr
        else:  # zscore
            mu, sigma = df[col].mean(), df[col].std()
            lo, hi = mu - factor * sigma, mu + factor * sigma
        clipped = df[col].clip(lo, hi)
        n_clipped = (df[col] != clipped).sum()
        if n_clipped:
            print(f"  {col}: clipped {n_clipped} outliers [{lo:.2f}, {hi:.2f}]")
        df[col] = clipped
    return df


def handle_missing(df: pd.DataFrame, strategy: str = "median",
                   threshold: float = 0.5) -> pd.DataFrame:
    """
    Two-phase missing-value handling:
      1. Drop columns where missingness > threshold
      2. Impute remaining with strategy (mean / median / mode / knn)
    """
    df = df.copy()
    miss_rate = df.isnull().mean()
    drop_cols = miss_rate[miss_rate > threshold].index.tolist()
    if drop_cols:
        print(f"  Dropping {len(drop_cols)} columns with >{threshold:.0%} missing: {drop_cols}")
        df = df.drop(columns=drop_cols)

    numeric_cols = df.select_dtypes(include=np.number).columns
    if strategy == "knn":
        from sklearn.impute import KNNImputer
        imp = KNNImputer(n_neighbors=5)
        df[numeric_cols] = imp.fit_transform(df[numeric_cols])
    else:
        fill_fn = {"mean": df[numeric_cols].mean, "median": df[numeric_cols].median}
        fills = fill_fn.get(strategy, df[numeric_cols].median)()
        df[numeric_cols] = df[numeric_cols].fillna(fills)
    print(f"  Imputed remaining missing values with strategy='{strategy}'")
    return df


def clean_dataset(df: pd.DataFrame,
                  outlier_method: str = "iqr",
                  impute_strategy: str = "median",
                  drop_missing_threshold: float = 0.5,
                  drop_correlated_threshold: float = 0.95) -> pd.DataFrame:
    """Full cleaning pipeline: outliers -> missing -> correlation -> type coercion."""
    print(f"Input shape: {df.shape}")
    df = handle_outliers(df, method=outlier_method)
    df = handle_missing(df, strategy=impute_strategy, threshold=drop_missing_threshold)

    # Remove highly correlated features (keep first of each pair)
    numeric = df.select_dtypes(include=np.number)
    corr = numeric.corr().abs()
    upper = corr.where(np.triu(np.ones(corr.shape), k=1).astype(bool))
    drop_cols = [c for c in upper.columns if any(upper[c] > drop_correlated_threshold)]
    if drop_cols:
        print(f"  Dropping {len(drop_cols)} highly correlated columns: {drop_cols}")
        df = df.drop(columns=drop_cols)

    print(f"Output shape: {df.shape}")
    return df
